#!/usr/bin/env node
/**
 * Generate dist/plugin.js — the Hermes DESKTOP app plugin — from the shared
 * dashboard bundle, so both hosts render the same UI from one source:
 *
 *   head.js + ../dashboard/dist/index.js + notifications.mjs + tail.js
 *   (SDK wiring, dashboard, pure notification helpers, registration; CSS inlined)
 *
 * Run after any dashboard change:  node packages/hermes-plugin/desktop/build.mjs
 * Hermes loads desktop/plugin.js from the installed package and copies it
 * into the app's desktop-plugins folder itself.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const read = p => readFileSync(join(here, p), 'utf8')

const css = read('theme-map.css') + '\n' + read('../dashboard/dist/style.css')
const tail = read('tail.js').replace('__PLUGIN_CSS__', () => JSON.stringify(css))
// The web dashboard falls back to localStorage. The desktop bundle must not:
// Hermes reviews desktop/plugin.js, and that half persists with ctx.storage.
const dashboard = read('../dashboard/dist/index.js')
  .replace(
    'try { window.localStorage.setItem(key, typeof value === "string" ? value : JSON.stringify(value)); }\n    catch (e) { /* noop */ }',
    '/* desktop persist is ctx.storage */'
  )
  .replace(
    'try { return JSON.parse(window.localStorage.getItem(key) || "{}") || {}; }\n    catch (e) { return {}; }',
    'return {};'
  )

const out = [
  '// GENERATED by desktop/build.mjs — do not edit. Sources: desktop/head.js,',
  '// dashboard/dist/index.js, desktop/notifications.mjs, desktop/tail.js',
  '// (+ theme-map.css, style.css).',
  read('head.js'),
  dashboard,
  read('notifications.mjs'),
  tail
  // Defensive statement separator: a fragment ending without `;` must not
  // swallow the next fragment's leading `(` (ASI would parse it as a call).
].join('\n;\n')

writeFileSync(join(here, 'plugin.js'), out)
console.log(`wrote desktop/plugin.js (${(out.length / 1024).toFixed(0)} KB)`)
